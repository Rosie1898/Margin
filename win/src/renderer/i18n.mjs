/** Translate application-owned UI only; unknown document/user text is preserved. */
export function t(text, language = 'system', values = [], depth = 0) {
  const original = String(text ?? '');
  // HTML data attributes contain literal backslash-n while JavaScript uses LF.
  const key = original.replaceAll('\\n', '\n');
  const resolved = resolveLanguage(language);
  const dictionary = catalog[resolved];
  const lookup = candidate => {
    if (Object.hasOwn(dictionary, candidate)) return windowsWording(dictionary[candidate], resolved);
    if (Object.hasOwn(catalog.en, candidate)) return resolved === 'zhHans' ? windowsWording(candidate, resolved) : windowsWording(catalog.en[candidate], 'en');
    return undefined;
  };
  const interpolate = (value, replacements) => value.replace(/\{(\d+)\}/g, (whole, index) => replacements[index] === undefined ? whole : String(replacements[index]));
  const exact = lookup(key);
  if (exact !== undefined) return interpolate(exact, values);
  const trimmed = lookup(key.trim());
  if (trimmed !== undefined) return key.match(/^\s*/)[0] + interpolate(trimmed, values) + key.match(/\s*$/)[0];
  // The shared account service replaces the macOS credential-store name before
  // delivering status. Match the original keys, then render Windows wording.
  const canonical = key.replaceAll('Windows 凭据存储', '钥匙串');
  const canonicalExact = lookup(canonical);
  if (canonicalExact !== undefined) return interpolate(canonicalExact, values);
  if (depth < 4) for (const template of messageTemplates) {
    const match = template.pattern.exec(canonical);
    if (!match) continue;
    if (template.numeric && !match.slice(1).every(value => /^\d+$/.test(value))) continue;
    const replacements = [];
    template.slots.forEach((slot, index) => { replacements[slot] = t(match[index + 1], resolved, [], depth + 1); });
    return interpolate(lookup(template.key), replacements);
  }
  const prefix = '暂时无法恢复登录，已保留钥匙串中的凭据。';
  if (canonical.startsWith(prefix) && lookup(prefix)) return lookup(prefix) + ' ' + t(canonical.slice(prefix.length), resolved, [], depth + 1);
  return original;
}
