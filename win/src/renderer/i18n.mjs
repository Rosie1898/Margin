/** Honor Chinese script first, then region, matching the macOS language resolver. */
export function resolveLanguage(language = 'system', preferredLanguages = systemLocales?.length ? systemLocales : globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? 'en']) {
  if (language !== 'system') {
    if (Object.hasOwn(catalog, language)) return language;
    preferredLanguages = [language];
  }
  for (const identifier of preferredLanguages) {
    const parts = String(identifier).replaceAll('_', '-').toLowerCase().split('-');
    if (parts[0] === 'zh') {
      if (parts.includes('hans')) return 'zhHans';
      return parts.some(part => ['hant', 'tw', 'hk', 'mo'].includes(part)) ? 'zhHant' : 'zhHans';
    }
    if (Object.hasOwn(catalog, parts[0])) return parts[0];
  }
  return 'en';
}

